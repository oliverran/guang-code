import assert from 'node:assert/strict';
import { spawn, spawnSync } from 'node:child_process';
import { cp, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import test from 'node:test';
import { parseTutorialArgs } from '../scripts/tutorial.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const launcher = path.join(root, 'scripts/tutorial.mjs');
const fixture = path.join(root, 'examples/cart-total/cart.js');
async function isolated(t) {
  const home = await mkdtemp(path.join(os.tmpdir(), 'guang-tutorial-test-'));
  t.after(() => rm(home, { recursive: true, force: true }));
  return { home, env: {
    HOME: home, USERPROFILE: home, TMPDIR: home, TMP: home, TEMP: home,
    PATH: '', NO_COLOR: '1',
    ...(process.env.SystemRoot ? { SystemRoot: process.env.SystemRoot } : {}),
  } };
}
function run(args, env) {
  return spawnSync(process.execPath, [launcher, ...args], {
    env, cwd: root, encoding: 'utf8', timeout: 15000,
  });
}
function success(result) {
  assert.ifError(result.error);
  assert.equal(result.status, 0, result.stdout + result.stderr);
}
async function noWorkspace(home) {
  assert.deepEqual((await readdir(home)).filter(name => name.startsWith('guang-tutorial-')), []);
}

test('tutorial args reject unknown options and positional project paths', () => {
  assert.equal(parseTutorialArgs([]).auto, false);
  assert.equal(parseTutorialArgs(['--auto']).auto, true);
  for (const args of [['--cwd', '.'], ['--yes'], ['--auto=false'], ['.']]) {
    assert.throws(() => parseTutorialArgs(args));
  }
});

test('help and invalid/non-TTY invocations create no exercise directory', async t => {
  const { home, env } = await isolated(t);
  const help = run(['--help'], env);
  success(help);
  assert.match(help.stdout, /NOT generated by an AI model/);
  for (const args of [[], ['--typo']]) {
    const result = run(args, env);
    assert.equal(result.status, 1);
    assert.match(result.stderr, /terminal|Unknown option/);
  }
  await noWorkspace(home);
});

test('auto mode executes real red/green tests and leaves the source and user home unchanged', async t => {
  const { home, env } = await isolated(t);
  const original = await readFile(fixture, 'utf8');
  const config = path.join(home, '.guang-code');
  await mkdir(config);
  await writeFile(path.join(config, 'config.json'), 'not valid json: must not be read');
  for (let i = 0; i < 2; i++) {
    const result = run(['--auto'], {
      ...env, OPENAI_API_KEY: 'credential-canary-do-not-print', GC_BASE_URL: 'http://invalid.invalid',
      // The separate allowlist test below checks that this is not inherited.
      NODE_OPTIONS: '--no-warnings',
    });
    success(result);
    assert.match(result.stdout, /AUTO: even final approval is a scripted answer/);
    assert.match(result.stdout, /# pass 2\b/);
    assert.match(result.stdout, /# fail 2\b/);
    assert.match(result.stdout, /Plan mode left the file unchanged/);
    assert.match(result.stdout, /denied requests never reached Edit/);
    assert.match(result.stdout, /# pass 4\b/);
    assert.match(result.stdout, /# fail 0\b/);
    assert.match(result.stdout, /PASS: red tests/);
    assert.doesNotMatch(result.stdout + result.stderr, /credential-canary|not valid json/);
    assert.equal(await readFile(fixture, 'utf8'), original);
    await noWorkspace(home);
  }
  assert.equal(await readFile(path.join(config, 'config.json'), 'utf8'), 'not valid json: must not be read');
});

async function interactive(t, answers, { signal, eof } = {}) {
  const { home, env } = await isolated(t);
  // Only the test harness marks its input as a terminal. Production CLI still
  // rejects piped input; the worker uses the actual readline question path.
  const source = `process.stdin.isTTY = true; const {main} = await import(${JSON.stringify(pathToFileURL(launcher).href)}); process.exitCode = await main([]);`;
  const child = spawn(process.execPath, ['--input-type=module', '-e', source], {
    cwd: root, env, stdio: ['pipe', 'pipe', 'pipe'],
  });
  let output = '', stderr = '', position = 0, promptCount = 0;
  const prompt = /Press Enter to continue, or q to quit: |What is ignored\? \[1\] price \[2\] quantity \(Enter reveals\): |Apply this patch\? Type y to approve; Enter\/n to decline: /g;
  const timer = setTimeout(() => child.kill('SIGKILL'), 12000);
  t.after(() => { clearTimeout(timer); if (child.exitCode === null) child.kill('SIGKILL'); });
  child.stdout.on('data', data => {
    output += data;
    prompt.lastIndex = position;
    let match;
    while ((match = prompt.exec(output))) {
      position = prompt.lastIndex;
      if (signal) { child.kill(signal); return; }
      if (eof) { child.stdin.end(); return; }
      const answer = answers[promptCount++];
      if (answer === undefined) { child.stdin.end(); return; }
      child.stdin.write(answer + '\n');
    }
  });
  child.stderr.on('data', data => { stderr += data; });
  const result = await new Promise((resolve, reject) => {
    child.once('error', reject);
    child.once('exit', (code, signal) => resolve({ code, signal }));
  });
  clearTimeout(timer);
  await noWorkspace(home);
  return { ...result, output, stderr };
}

test('interactive approval runs the final tests', async t => {
  const result = await interactive(t, ['', '', '2', '', '', 'y', '']);
  assert.equal(result.code, 0, result.output + result.stderr);
  assert.match(result.output, /PASS: red tests/);
  assert.doesNotMatch(result.output, /scripted answer/);
});

for (const answer of ['', 'n', 'yes', 'unexpected']) {
  test(`final edit requires the exact y choice (${JSON.stringify(answer)})`, async t => {
    const result = await interactive(t, ['', '', '1', '', '', answer]);
    assert.equal(result.code, 0, result.output + result.stderr);
    assert.match(result.output, /Declined\. No edit was performed/);
    assert.doesNotMatch(result.output, /File edited successfully|# pass 4\b/);
  });
}

test('quit, closed input, and a handled signal clean the temporary exercise', async t => {
  for (const options of [{ answers: ['q'] }, { answers: [], eof: true }, { answers: [], signal: 'SIGTERM' }]) {
    const result = await interactive(t, options.answers, options);
    assert.equal(result.code, options.signal ? 130 : 0, result.output + result.stderr);
    assert.doesNotMatch(result.output, /File edited successfully/);
    assert.match(result.output, /Temporary exercise removed/);
  }
});

test('direct worker use cannot edit the committed example', async t => {
  const { env } = await isolated(t);
  const original = await readFile(fixture, 'utf8');
  const result = spawnSync(process.execPath, [path.join(root, 'scripts/tutorial-worker.mjs'), '--auto'], {
    cwd: path.dirname(fixture), env, encoding: 'utf8', timeout: 10000,
  });
  assert.equal(result.status, 1);
  assert.match(result.stderr, /Use npm run tutorial/);
  assert.equal(await readFile(fixture, 'utf8'), original);
});

test('launcher drops credential and Node injection variables before starting worker', async t => {
  const { home, env } = await isolated(t);
  const copy = path.join(home, 'launcher-copy');
  await mkdir(path.join(copy, 'scripts'), { recursive: true });
  await mkdir(path.join(copy, 'examples'), { recursive: true });
  await cp(launcher, path.join(copy, 'scripts/tutorial.mjs'));
  await cp(path.join(root, 'examples/cart-total'), path.join(copy, 'examples/cart-total'), { recursive: true });
  await writeFile(path.join(copy, 'scripts/tutorial-worker.mjs'), `
    import assert from 'node:assert/strict';
    for (const key of ['OPENAI_API_KEY', 'ANTHROPIC_API_KEY', 'GC_API_KEY', 'NODE_OPTIONS', 'GC_BASE_URL']) {
      assert.equal(process.env[key], undefined, key);
    }
    assert.equal(process.env.PATH, '');
    assert.equal(process.env.GUANG_TUTORIAL_WORKSPACE, process.cwd());
    assert.notEqual(process.env.HOME, ${JSON.stringify(home)});
    console.log('environment allowlist verified');
  `);
  const result = spawnSync(process.execPath, [path.join(copy, 'scripts/tutorial.mjs'), '--auto'], {
    env: { ...env, NODE_OPTIONS: '--no-warnings', OPENAI_API_KEY: 'fake-canary',
      ANTHROPIC_API_KEY: 'fake-canary', GC_API_KEY: 'fake-canary', GC_BASE_URL: 'http://invalid.invalid' },
    encoding: 'utf8', timeout: 10000,
  });
  success(result);
  assert.match(result.stdout, /environment allowlist verified/);
  await noWorkspace(home);
});

test('offline worker completes with network entrypoints disabled', async t => {
  const { home, env } = await isolated(t);
  const project = path.join(home, 'network-disabled-practice');
  await cp(path.join(root, 'examples/cart-total'), project, { recursive: true });
  const source = `
    import http from 'node:http';
    import https from 'node:https';
    import net from 'node:net';
    import tls from 'node:tls';
    import { syncBuiltinESMExports } from 'node:module';
    const deny = () => { throw new Error('Network is forbidden in the offline tutorial'); };
    globalThis.fetch = deny;
    http.request = http.get = https.request = https.get = deny;
    net.connect = net.createConnection = tls.connect = deny;
    net.Socket.prototype.connect = deny;
    syncBuiltinESMExports();
    process.argv.push('--auto');
    await import(${JSON.stringify(pathToFileURL(path.join(root, 'scripts/tutorial-worker.mjs')).href)});
  `;
  const result = spawnSync(process.execPath, ['--input-type=module', '-e', source], {
    cwd: project, env: { ...env, GUANG_TUTORIAL_WORKSPACE: project },
    encoding: 'utf8', timeout: 10000,
  });
  success(result);
  assert.match(result.stdout, /PASS: red tests/);
});
