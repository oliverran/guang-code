/**
 * Publish the DSH editable surface as a manifest both trees read.
 *
 * The surface is defined once, in `@deepseek-ai/dsh-ppc-surface`, and harness2's Python
 * substrate reads the same values from the manifest this script writes. Two independent
 * definitions of the same editable surface drift: a path one tree accepts and the other
 * rejects is a proposal that validates in one place and is discarded in the other.
 *
 * The manifest is JSON so the Python side needs no parser of its own.
 *
 *   `tsx scripts/gen-ppc-surface.ts`          -> write the manifest
 *   `tsx scripts/gen-ppc-surface.ts --check`  -> exit 1 when it is stale
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { DSH_SURFACE } from '../packages/ppc/ppc-surface/src/index.ts'

const root = resolve(import.meta.dirname, '..')
const OUT = 'packages/ppc/ppc-surface/surface-manifest.json'

/**
 * Render the surface as the manifest both trees read.
 *
 * The manifest carries the rules a substrate needs to accept, validate, and stage a
 * proposal; it carries no prose beyond the always-on cap reason, which a proposer is shown.
 * @returns the manifest text.
 */
export function renderManifest(): string {
  const surface = DSH_SURFACE
  const manifest = {
    $comment: 'Generated by scripts/gen-ppc-surface.ts — do not edit by hand.',
    name: surface.name,
    alwaysOn: surface.alwaysOn,
    alwaysOnMax: surface.alwaysOnMax,
    alwaysOnCapReason: surface.alwaysOnCapReason,
    skillDir: surface.skillDir,
    skillNameRule: surface.skillNameRule,
    scriptDir: surface.scriptDir,
    skillScriptDir: surface.skillScriptDir,
    autotriggerFile: surface.autotriggerFile,
    triggerLine: surface.triggerLine,
    triggerHint: surface.triggerHint,
    pluginDir: surface.pluginDir ?? null,
    subagentDir: surface.subagentDir ?? null,
    subagentRequiresMode: surface.subagentRequiresMode,
    compileSkillScripts: surface.compileSkillScripts,
    hooksFile: surface.hooksFile,
    hookEvents: surface.hookEvents,
    rejectEmptyAlwaysOn: surface.rejectEmptyAlwaysOn,
    stubs: surface.stubs.map(([path, body]) => ({ path, body })),
  }
  return `${JSON.stringify(manifest, null, 2)}\n`
}

/** CLI entry: default writes the manifest, `--check` fails if the committed copy is stale. */
function main(): void {
  const content = renderManifest()
  if (process.argv.includes('--check')) {
    let committed: string | null = null
    try {
      committed = readFileSync(resolve(root, OUT), 'utf8')
    } catch {
      // A missing manifest is a stale manifest: the remedy is the same — regenerate.
      committed = null
    }
    if (committed === content) {
      console.log(`gen-ppc-surface: ${OUT} is up to date.`)
      process.exit(0)
    }
    console.error(`gen-ppc-surface: ${OUT} is stale. Run \`pnpm run gen-ppc-surface\` and commit ${OUT}.`)
    process.exit(1)
  }
  writeFileSync(resolve(root, OUT), content)
  console.log(`gen-ppc-surface: wrote ${OUT}.`)
}

if (process.argv[1] && import.meta.filename === resolve(process.argv[1])) {
  main()
}
