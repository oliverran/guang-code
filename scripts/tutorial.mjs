// Launch the fixed, credential-free exercise in an isolated child process.
// No provider, configuration, plugin, or QueryEngine imports belong here.
import { spawn } from 'node:child_process';
import { cp, mkdir, mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

const root = fileURLToPath(new URL('../', import.meta.url));
export const HELP = `Usage: npm run tutorial -- [--auto | --help]

A guided, offline exercise using Guang Code's real local tools.
No API key, model call, user project, shell command, or web server is used.
The tool sequence and repair are scripted, NOT generated by an AI model.

  --auto       Run all steps with scripted answers, including edit approval
  -h, --help   Show help without creating files or loading tool dependencies

Interactive mode requires a terminal. Enter q at a prompt to quit.
Each run copies examples/cart-total into a fresh temporary directory and
removes that directory on completion, cancellation, or a handled signal.
See docs/tutorial.md to use the example with your own model instead.
`;

export function parseTutorialArgs(args) {
  return parseArgs({ args, allowPositionals: false, strict: true, options: {
    auto: { type: 'boolean', default: false },
    help: { type: 'boolean', short: 'h', default: false },
  } }).values;
}

export async function main(args = process.argv.slice(2)) {
  const options = parseTutorialArgs(args);
  if (options.help) { process.stdout.write(HELP); return 0; }
  if (!options.auto && !process.stdin.isTTY) {
    throw new Error('Interactive mode needs a terminal. Use --auto for the explicitly scripted run.');
  }
  const temp = await mkdtemp(path.join(os.tmpdir(), 'guang-tutorial-'));
  const project = path.join(temp, 'project');
  const home = path.join(temp, 'home');
  let child;
  let signalReceived;
  const stop = signal => {
    signalReceived = signal;
    child?.kill(signal);
  };
  const onInt = () => stop('SIGINT');
  const onTerm = () => stop('SIGTERM');
  process.on('SIGINT', onInt);
  process.on('SIGTERM', onTerm);
  try {
    await mkdir(home);
    await cp(path.join(root, 'examples/cart-total'), project, { recursive: true });
    if (signalReceived) return 130;
    // An allowlist, not {...process.env}: no keys, NODE_OPTIONS, user config,
    // shell startup files, proxy settings, or external rg executable.
    const env = {
      HOME: home, USERPROFILE: home, PATH: '', NO_COLOR: '1',
      TMPDIR: temp, TMP: temp, TEMP: temp,
      GUANG_TUTORIAL_WORKSPACE: project,
      ...(process.env.SystemRoot ? { SystemRoot: process.env.SystemRoot } : {}),
    };
    child = spawn(process.execPath, [
      path.join(root, 'scripts/tutorial-worker.mjs'), ...(options.auto ? ['--auto'] : []),
    ], { cwd: project, env, stdio: 'inherit' });
    const code = await new Promise((resolve, reject) => {
      child.once('error', reject);
      child.once('exit', (status, signal) => resolve(signal ? 130 : (status ?? 1)));
    });
    return signalReceived ? 130 : code;
  } finally {
    process.removeListener('SIGINT', onInt);
    process.removeListener('SIGTERM', onTerm);
    await rm(temp, { recursive: true, force: true });
    process.stdout.write('\nTemporary exercise removed. Your source example was not changed.\n');
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try { process.exitCode = await main(); }
  catch (error) { console.error(`Tutorial: ${error.message}`); process.exitCode = 1; }
}
